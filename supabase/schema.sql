-- Kanakku database schema. Paste this into Supabase → SQL Editor → Run.
-- The app fills in demo data automatically on the first request.

create table if not exists products (
  id            text primary key,
  name          text not null,
  name_ml       text not null default '',
  aliases       text[] not null default '{}',
  unit          text not null check (unit in ('kg','l','pc','pkt')),
  price         numeric not null default 0,
  stock         numeric not null default 0,
  low_stock_at  numeric not null default 0,
  category      text not null default 'Other',
  cost_price    numeric
);
-- For databases created before cost prices existed:
alter table products add column if not exists cost_price numeric;

create table if not exists customers (
  id          text primary key,
  name        text not null,
  name_ml     text,
  aliases     text[] not null default '{}',
  phone       text,
  created_at  timestamptz not null default now()
);

create table if not exists bills (
  id             text primary key,
  number         bigint generated by default as identity,
  created_at     timestamptz not null default now(),
  customer_id    text references customers(id) on delete set null,
  customer_name  text,
  items          jsonb not null default '[]',
  total          numeric not null default 0,
  payment_mode   text not null check (payment_mode in ('cash','upi','credit')),
  source         text not null,
  raw_input      text
);
create index if not exists bills_created_at on bills (created_at);
create index if not exists bills_customer on bills (customer_id);

create table if not exists payments (
  id           text primary key,
  created_at   timestamptz not null default now(),
  customer_id  text not null references customers(id) on delete cascade,
  amount       numeric not null,
  note         text,
  source       text not null default 'manual'
);

create table if not exists stock_moves (
  id          text primary key,
  created_at  timestamptz not null default now(),
  product_id  text not null references products(id) on delete cascade,
  qty         numeric not null,
  reason      text not null,
  source      text not null
);

-- Atomic stock change so two bills at the same moment never lose an update.
create or replace function adjust_stock(pid text, delta numeric)
returns void language sql as $$
  update products set stock = round(stock + delta, 3) where id = pid;
$$;

-- The app talks to Supabase from the server with the service role key,
-- so row level security stays on with no public policies.
alter table products    enable row level security;
alter table customers   enable row level security;
alter table bills       enable row level security;
alter table payments    enable row level security;
alter table stock_moves enable row level security;
