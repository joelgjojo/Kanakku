import type { Metadata } from "next";
import { businessReport } from "@/lib/analytics";
import { rupees } from "@/lib/format";
import { PrintButton } from "./PrintButton";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Business report · Kanakku" };

const fmtDate = (iso: string) => new Date(iso).toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });

// A 4-week summary from the shop's own records, written for a bank officer (MUDRA / small business loans).
export default async function Report() {
  const r = await businessReport();
  const figures = [
    { label: "Total sales", value: rupees(r.totalSales), note: `${r.daysTrading} trading days` },
    { label: "Average per day", value: rupees(r.avgDaily), note: `≈ ${rupees(r.monthlyRunRate)} a month` },
    { label: "Gross profit (est.)", value: r.marginPct === null ? "–" : rupees(r.grossProfit), note: r.marginPct === null ? "add supplier bills" : `${r.marginPct}% margin` },
    { label: "Growth", value: r.growthPct === null ? "–" : `${r.growthPct > 0 ? "+" : ""}${r.growthPct}%`, note: "last 2 weeks vs 2 before" },
  ];
  return (
    <article className="px-4 lg:px-8 py-6 max-w-4xl space-y-5 print:p-0 print:max-w-none">
      <header className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <p className="text-muted">Business summary from daily records</p>
          <h1 className="sign text-[2.4rem]">{r.shop}</h1>
          <p className="text-muted num">{fmtDate(r.from)} to {fmtDate(r.to)}</p>
        </div>
        <PrintButton />
      </header>

      <section className="grid grid-cols-2 lg:grid-cols-4 gap-3">
        {figures.map((f) => (
          <div key={f.label} className="panel p-4">
            <p className="text-sm text-muted">{f.label}</p>
            <p className="sign num text-3xl mt-1">{f.value}</p>
            <p className="text-xs text-muted mt-1">{f.note}</p>
          </div>
        ))}
      </section>

      <section className="panel p-5 grid gap-5 md:grid-cols-2">
        <div>
          <h2 className="font-semibold text-lg">Sales</h2>
          <dl className="mt-2 space-y-1.5 text-[0.95rem]">
            <Row k="Bills raised" v={String(r.bills)} />
            <Row k="Average bill" v={rupees(r.avgBill)} />
            <Row k="Best day" v={r.bestDay ? `${fmtDate(r.bestDay.date)} · ${rupees(r.bestDay.sales)}` : "–"} />
            <Row k="Day-to-day consistency" v={`${r.consistency}%`} />
            <Row k="Paid by UPI" v={`${r.digitalShare}% of sales`} />
            <Row k="Stock on hand (at cost)" v={rupees(r.stockValue)} />
          </dl>
        </div>
        <div>
          <h2 className="font-semibold text-lg">Customer credit (pattu)</h2>
          <dl className="mt-2 space-y-1.5 text-[0.95rem]">
            <Row k="Credit given" v={rupees(r.creditGiven)} />
            <Row k="Credit collected" v={rupees(r.creditCollected)} />
            <Row k="Collection rate" v={r.collectionRate === null ? "–" : `${r.collectionRate}%`} />
            <Row k="Outstanding today" v={rupees(r.outstanding)} />
            <Row k="Customers on credit" v={String(r.creditCustomers)} />
            <Row k="Rated reliable payers" v={`${r.reliableShare}%`} />
          </dl>
        </div>
      </section>

      <section className="panel p-5">
        <h2 className="font-semibold text-lg">Top items by sales</h2>
        <ol className="mt-2 space-y-1.5">
          {r.topItems.map((t, i) => (
            <li key={t.name} className="flex items-center gap-3">
              <span className="w-4 text-sm text-faint num">{i + 1}</span>
              <span className="flex-1">{t.name}</span>
              <span className="num text-muted">{rupees(t.revenue)}</span>
            </li>
          ))}
        </ol>
      </section>

      <p className="text-xs text-muted leading-relaxed">
        Generated by Kanakku on {fmtDate(r.to)} from the shop&apos;s own bill, payment and supplier records, captured by voice,
        WhatsApp and notebook photos. Profit is estimated from the latest supplier bill prices. Consistency shows how steady daily
        sales are (100% means the same every day).
      </p>
    </article>
  );
}

function Row({ k, v }: { k: string; v: string }) {
  return (
    <div className="flex justify-between gap-4 border-b border-line/70 pb-1.5">
      <dt className="text-muted">{k}</dt>
      <dd className="num font-semibold text-right">{v}</dd>
    </div>
  );
}
